namespace delosfera_server.Modules.Notifications.Models;

public enum NotificationCategory
{
    System = 0,        // Системные - обновления, тех. работы

    Vnd = 1,           // ВНД - новые редакции, статусы, согласования по ВНД

    // Approval и Task больше не используются для новых уведомлений и не показываются
    // отдельной вкладкой (см. NotificationCategoryCatalog) - только ВНД, СЗ и закупки
    // разошлись по своим категориям (Vnd/Sz/Procurement), остальное ушло в Other.
    // Значения оставлены как есть (не переиспользуются под новый смысл), чтобы у уже
    // сохранённых в БД уведомлений не "переехала" категория задним числом.
    Approval = 2,
    Task = 3,

    Other = 4,         // разное - напоминания по обязательствам, ознакомления, письма, встречи

    Sz = 5,            // Служебные записки - согласование, решение адресата, сроки
    Procurement = 6    // Закупки и договоры - согласование, статусы маршрута
}