namespace delosfera_server.Modules.Signing.Models;

/// <summary>
/// Настройки квалифицированной подписи: служба меток времени и проверка отзыва.
///
/// Хранятся в базе, а не в конфигурации сервера: адрес службы меток и точки
/// распространения списков отзыва даёт удостоверяющий центр, они меняются, и такая
/// правка не должна требовать доступа к серверу и перезапуска.
///
/// Запись одна на всю систему.
/// </summary>
public class SigningSettings
{
    public int Id { get; set; }

    // --- метка времени (RFC 3161) ---

    /// <summary>
    /// Ставить метку времени на подпись. Без метки нельзя доказать, что подпись
    /// поставлена, пока сертификат действовал: после истечения срока обе картины —
    /// «подписал вовремя» и «подписал позже» — выглядят одинаково.
    /// </summary>
    public bool TimestampEnabled { get; set; }

    /// <summary>Адрес службы меток времени удостоверяющего центра.</summary>
    public string? TimestampAuthorityUrl { get; set; }

    /// <summary>
    /// Отказывать в подписи, если метку получить не удалось. Выключено — подпись
    /// принимается без метки и помечается: связь со службой пропадает, а подписать
    /// приказ иногда нужно именно сейчас. Решение за банком, поэтому это настройка.
    /// </summary>
    public bool TimestampRequired { get; set; }

    public int TimestampTimeoutSeconds { get; set; } = 15;

    // --- отзыв сертификатов ---

    /// <summary>
    /// Проверять, не отозван ли сертификат. Точки распространения берутся из самого
    /// сертификата: удостоверяющий центр указывает их при выпуске.
    /// </summary>
    public bool RevocationCheckEnabled { get; set; }

    /// <summary>
    /// Отказывать, когда проверить отзыв не удалось — сеть недоступна, служба молчит.
    /// Строгий режим: неизвестное состояние считается отозванным. Для приказов это
    /// правильно, для рядовой визы — избыточно, поэтому выбирает банк.
    /// </summary>
    public bool RevocationStrict { get; set; }

    /// <summary>Как часто перепроверять уже закреплённые сертификаты сотрудников.</summary>
    public int RevocationRecheckHours { get; set; } = 24;

    public DateTime UpdatedAt { get; set; }
    public int? UpdatedByUserId { get; set; }
}
