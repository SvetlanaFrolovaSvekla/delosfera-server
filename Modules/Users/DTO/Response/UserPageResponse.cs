using delosfera_server.Common.Models;

namespace delosfera_server.Modules.Users.DTO.Response;

/// <summary>
/// Страница списка сотрудников.
///
/// Раньше список отдавался целиком: пятьсот сорок учётных записей с ролями,
/// должностью, подразделением и данными о блокировке — семьсот килобайт на
/// каждое открытие страницы, и дальше только больше вместе со штатом.
/// </summary>
public class UserPageResponse : PagedResult<UserResponse>
{
    /// <summary>
    /// Сколько всего сотрудников подходит под фильтры — по каждому состоянию.
    ///
    /// Считается без учёта выбранного состояния: вкладки «Все», «Работают» и
    /// «Заблокированы» должны показывать, сколько там записей, а не сколько их
    /// на открытой вкладке. По странице это посчитать нельзя, поэтому счёт
    /// приходит с сервера вместе с ней.
    /// </summary>
    public UserCounts Counts { get; set; } = new();
}

/// <summary>Сколько сотрудников в каждом состоянии при текущих фильтрах.</summary>
public class UserCounts
{
    public int All { get; set; }

    /// <summary>
    /// Работающими считаются те, кого не заблокировал администратор и кто активен
    /// сам по себе: отключённые в службе каталогов приходят неактивными, и считать
    /// их работающими значит показывать уволенных наравне с действующими.
    /// </summary>
    public int Active { get; set; }

    public int Blocked { get; set; }
}
