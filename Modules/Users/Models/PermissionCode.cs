namespace delosfera_server.Modules.Users.Models;

/// <summary>
/// Права доступа в системе. Фиксированный список - новые права добавляются только разработчиками.
/// </summary>
public enum PermissionCode
{
    /// <summary>Просмотр страницы актуализации ВНД</summary>
    ViewVndActualizationPage = 1,

    /// <summary>Взять любую ВНД в актуализацию с последующим согласованием (без запроса права)</summary>
    ActualizeAnyVndWithApproval = 2,

    /// <summary>Взять любую ВНД в актуализацию без согласования (без запроса права)</summary>
    ActualizeAnyVndWithoutApproval = 3,

    /// <summary>Взять ВНД в актуализацию с последующим согласованием (по запросу права)</summary>
    ActualizeVndWithApprovalByRequest = 4,

    /// <summary>Взять ВНД в актуализацию без согласования (по запросу права)</summary>
    ActualizeVndWithoutApprovalByRequest = 5,

    /// <summary>Создать новую ВНД с последующим согласованием</summary>
    CreateVndWithApproval = 6,

    /// <summary>Создать новую ВНД без последующего согласования</summary>
    CreateVndWithoutApproval = 7,

    /// <summary>Удалить ВНД</summary>
    DeleteVnd = 8,

    /// <summary>Редактировать последнюю редакцию без согласования, без создания новой редакции и изменения даты актуализации</summary>
    EditLastRevisionDirectly = 9,

    /// <summary>Управление группами</summary>
    ManageGroups = 10,

    /// <summary>Просмотр ВНД</summary>
    ViewVnd = 11,

    /// <summary>Экспорт ВНД</summary>
    ExportVnd = 12,

    /// <summary>Управление пользователями</summary>
    ManageUsers = 13,

    /// <summary>Управление ролями</summary>
    ManageRoles = 14,

    /// <summary>Просмотр ограниченной статистики</summary>
    ViewLimitedStatistics = 15,

    /// <summary>Экспорт отчёта по полной статистике</summary>
    ExportFullStatisticsReport = 16,

    /// <summary>Просмотр полной статистики</summary>
    ViewFullStatistics = 17,

    /// <summary>Возможность выступать в роли согласующего</summary>
    ActAsApprover = 18,

    /// <summary>Возможность изменять маршрут согласования (удалять лишних пользователей)</summary>
    ModifyApprovalRoute = 19,

    /// <summary>Возможность просматривать черновики других пользователей</summary>
    ViewOtherUsersDrafts = 20,

    /// <summary>Управление справочниками ВНД (Виды ВНД, Уровни секретности, Группы пользователей,
    /// Рубрикатор, Обязательные участники согласования, ключевые слова)</summary>
    ManageVndDictionaries = 21,

    /// <summary>Управление общими справочниками (Органы утверждения, Структурные подразделения, Должности)</summary>
    ManageGeneralDictionaries = 22,

    /// <summary>Управление справочниками служебных записок (Категории СЗ)</summary>
    ManageSzDictionaries = 23,

    /// <summary>Управление справочниками закупок (Чёрный список контрагентов, Пороги закупок)</summary>
    ManageProcurementDictionaries = 24,

    /// <summary>Изменение реквизитов уже существующей ВНД (кнопка "Изменить реквизиты")
    /// и её связей с другими документами — в отличие от Create*, не про создание, а про
    /// редактирование метаданных того, что уже есть</summary>
    EditVndRequisites = 25,

    /// <summary>Доступ к разделу «Заседания». Повестку целиком при этом видит только член
    /// органа или его секретарь — остальным видны лишь вопросы, где они указаны</summary>
    ViewMeetings = 26,

    /// <summary>Ведение заседаний Правления — роль Секретаря Правления</summary>
    ManageBoardMeetings = 27,

    /// <summary>Ведение заседаний КПА — роль Секретаря КПА</summary>
    ManageKpaMeetings = 28,

    /// <summary>Ведение заседаний Кредитного комитета</summary>
    ManageCreditCommitteeMeetings = 29,

    /// <summary>Заполнение отчёта об исполнении и статуса поручений (УРПК, УРПС, юристы филиалов) —
    /// единственные поля вопроса повестки, доступные исполнителю на изменение</summary>
    ReportMeetingExecution = 30,

    /// <summary>Выгрузка реестра решений в Excel — доступна секретарям</summary>
    ExportMeetingRegistry = 31,

    /// <summary>Член Правления — видит повестку Правления целиком и получает уведомления о заседаниях</summary>
    MemberOfBoard = 32,

    /// <summary>Член КПА — видит повестку КПА целиком и получает уведомления о заседаниях</summary>
    MemberOfKpa = 33,

    /// <summary>Член Кредитного комитета — видит повестку КИТ целиком и получает уведомления</summary>
    MemberOfCreditCommittee = 34,

    /// <summary>
    /// Системные настройки: связь со службой каталогов и прочие параметры интеграций.
    /// Право отделено от управления ролями: настройки содержат пароль сервисной
    /// учётной записи, и круг допущенных к ним уже.
    /// </summary>
    ManageSystemSettings = 35,

    /// <summary>
    /// Просмотр реестра ВНД в расширенном режиме: колонки и фильтры "Статус последней
    /// редакции" и "Актуализация". Без этого права пользователь видит реестр без них.
    /// </summary>
    ViewVndRegistryExtended = 36,

/// Просмотр реестра доверенностей. Отделено от ведения: вопрос «вправе ли этот
    /// человек подписать» задают многие — юристы, закупки, делопроизводство, — а
    /// выдают доверенности единицы.
    /// </summary>
    ViewPowersOfAttorney = 37,

    /// <summary>Ведение доверенностей: заведение, выдача, отзыв, передоверие.</summary>
    ManagePowersOfAttorney = 38,

    /// <summary>
    /// Просмотр книги регистрации корреспонденции. Письма по счетам клиентов
    /// сюда не входят — они закрыты отдельно, банковской тайной.
    /// </summary>
    ViewCorrespondence = 39,

    /// <summary>Регистрация писем и ведение справочника корреспондентов — делопроизводство.</summary>
    RegisterCorrespondence = 40,

    /// <summary>
    /// Доступ к запросам по счетам и операциям клиентов. Отдельное право, а не
    /// часть общего: банковская тайна — это узкий круг допущенных, и он не совпадает
    /// с кругом тех, кто читает обычную переписку.
    /// </summary>
    ViewBankSecrecyInquiries = 41,

    /// <summary>
    /// Просмотр книги приказов по личному составу. Свою кадровую историю сотрудник
    /// видит и без этого права — это сведения о нём самом.
    /// </summary>
    ViewHrOrders = 42,

    /// <summary>Издание кадровых приказов — кадровая служба.</summary>
    ManageHrOrders = 43,

    /// <summary>
    /// Отозвать согласование любой ВНД, не будучи её инициатором (роль главного
    /// редактора). Без этого права отозвать согласование может только сам инициатор.
    ///
    /// Номер 44, а не 37, под которым право завели при разработке: 37 на стенде
    /// уже означает доступ к доверенностям и выдан семи ролям. Оставь мы 37 — те
    /// же люди молча получили бы право отзывать чужие согласования, а доверенности
    /// у них пропали бы. Ошибка без единого сообщения: число то же, смысл другой.
    ///
    /// Отсюда правило: номер, попавший на стенд, не переиспользуется никогда.
    /// Новое право берёт следующий свободный, даже если в середине есть дыры.
    /// </summary>
    CancelAnyVndApproval = 44,

    // ── Закупки ──────────────────────────────────────────────────────────────
    //
    // До этих прав модуль закупок закрывался одной проверкой «вошёл в систему»:
    // любой сотрудник мог собрать комиссию, внести за неё голоса и объявить
    // победителя. Права разделены по ролям процесса, как он идёт на деле:
    // подразделение заводит заявку, УПиА смотрит бюджет, Сектор закупок ведёт
    // процедуру, секретарь комиссии оформляет её решения.
    //
    // Заявку заводит любой сотрудник — отдельного права на это нет намеренно:
    // потребность в закупке возникает у любого подразделения, и запирать её
    // значит вернуть заявки в почту.

    /// <summary>Видеть чужие закупки в реестре, а не только свои.</summary>
    ViewAllProcurements = 45,

    /// <summary>
    /// Вести закупочную процедуру: конкурс, состав комиссии, публикация,
    /// регистрация заявок, вскрытие. Право Сектора закупок как организатора.
    /// </summary>
    ConductProcurement = 46,

    /// <summary>
    /// Вносить решения комиссии: явку, голоса, особые мнения, заключения
    /// экспертов. Право секретаря комиссии — он ведёт протокол заседания.
    /// </summary>
    RecordCommissionDecisions = 47,

    /// <summary>Формировать и пересобирать протокол закупки.</summary>
    ManageProcurementProtocol = 48,

    /// <summary>Вести договоры по итогам закупок, акты и претензии.</summary>
    ManageProcurementContracts = 49,

    /// <summary>Вести План закупок: позиции, утверждение, отчёт об исполнении.</summary>
    ManageProcurementPlan = 50,

    /// <summary>Вести реестр поставщиков и чёрный список недобросовестных.</summary>
    ManageSuppliers = 51,

    /// <summary>
    /// Видеть все служебные записки банка, а не только свои и своего подразделения.
    ///
    /// Право Председателя Правления, его заместителей и Сектора делопроизводства.
    /// Чужие черновики не показываются и им: черновик — ещё не документ, и автор
    /// вправе передумать, не объясняясь.
    ///
    /// Руководителю подразделения это право не нужно: записки своего подразделения
    /// он видит по самому факту руководства, а не по выданному признаку — иначе
    /// каждое назначение начальника требовало бы ещё и правки прав.
    /// </summary>
    ViewAllSz = 52,

    /// <summary>
    /// Регистрировать служебные записки: присваивать номер согласованной записке
    /// и передавать её подписанту. Право Сектора делопроизводства.
    ///
    /// До этого права регистрация не была защищена ничем: любой сотрудник,
    /// открывший карточку в статусе «Ждёт регистрации», видел кнопку и мог
    /// присвоить записке номер в общей книге регистрации.
    /// </summary>
    RegisterSz = 53,

    /// <summary>
    /// Консолидировать согласованную редакцию любой ВНД (перевод Consolidation → Active),
    /// не будучи ни ответственным за текущий цикл актуализации, ни инициатором согласования.
    /// Право главного методолога.
    ///
    /// До этого права VndActualizationService.PublishAsync пускал сюда же любого, у кого
    /// есть одно из прав CreateVndWith(out)Approval / ActualizeAnyVndWith(out)Approval
    /// ("главный редактор" — умышленно широкий набор для остальных шагов актуализации), из-за
    /// чего консолидировать чужую редакцию мог практически любой автор ВНД, а не только тот,
    /// кто отвечает за приёмку. Это право узкое и используется только в PublishAsync.
    /// </summary>
    ConsolidateAnyVnd = 54,

    /// <summary>
    /// Архивировать (отменить) ВНД — кнопка "Архивировать" в карточке документа, доступна на
    /// любом статусе, кроме черновика (тот только удаляется) и уже архивированного. Оформляется
    /// № и датой отмены (служебная записка), без согласования — см. VndService.CancelAsync.
    ///
    /// Если на момент архивации документ "На согласовании" — согласование отзывается
    /// автоматически в рамках той же операции (см. VndApprovalService.WithdrawForCancelAsync);
    /// само право CancelVnd тут достаточное основание, отдельно иметь ещё и
    /// CancelAnyVndApproval архивирующему не требуется. Право узкое и намеренно отделено от
    /// CancelAnyVndApproval — то отзывает согласование конкретной редакции, это архивирует
    /// документ целиком.
    /// </summary>
    CancelVnd = 55,

    /// <summary>
    /// Выносить служебные записки на коллегиальный орган.
    ///
    /// Право Председателя Правления и исполняющего его обязанности. Начальник
    /// управления, которому записка адресована, отписывает её исполнителям, но
    /// вопрос на Правление не выносит — это не его уровень.
    ///
    /// Правом, а не должностью: должности приходят из портала и называются
    /// по-разному, а «исполняющий обязанности» в справочнике должностей вообще
    /// не отражается.
    /// </summary>
    SubmitSzToBody = 56
}