using delosfera_server.Modules.Users.Models;

namespace delosfera_server.Modules.Settings.Models;

/// <summary>Что сделали с настройкой.</summary>
public enum SettingsChangeKind
{
    Added = 1,
    Modified = 2,
    Deleted = 3,
}

/// <summary>
/// Изменение настройки или справочника.
///
/// Отдельный журнал, а не общий с действиями по документам. Вопросы к ним разные:
/// к документу — «что происходило с этой запиской», к настройкам — «кто и когда
/// поменял справочник, из-за которого всё поехало». Второй задают редко, но
/// отвечать на него нужно за любой прошлый день, и искать ответ в потоке
/// документных событий бесполезно.
///
/// Записи собирает сам контекст базы при сохранении, а не каждая служба
/// справочника отдельно. Справочников девять, служб у них девять же, и добавить
/// десятый, забыв про запись в журнал, — вопрос времени.
/// </summary>
public class SettingsChange
{
    public long Id { get; set; }

    /// <summary>
    /// Что менялось: «Подразделения», «Роли», «Виды ВНД». Человеческое название,
    /// а не имя класса — журнал читает администратор банка.
    /// </summary>
    public required string Area { get; set; }

    /// <summary>Имя сущности в коде — по нему отбирают программно.</summary>
    public required string EntityType { get; set; }

    public int EntityId { get; set; }

    /// <summary>
    /// Название записи на момент изменения. Хранится снимком: удалённую запись
    /// иначе не назвать, а «удалили подразделение № 47» ничего не объясняет.
    /// </summary>
    public string? EntityTitle { get; set; }

    public SettingsChangeKind Kind { get; set; }

    /// <summary>
    /// Что именно поменялось: поле, старое значение, новое. Только изменённые
    /// поля — писать всю запись целиком значит хоронить одну правку в тридцати
    /// неизменных строках.
    /// </summary>
    public string? ChangesJson { get; set; }

    /// <summary>
    /// Кто менял. Внешнего ключа на пользователя намеренно нет: журнал не должен
    /// ломаться оттого, что учётную запись удалили, — и тем более не должен
    /// ронять само сохранение справочника, если в токене оказался номер, которого
    /// в базе уже нет. Журнал наблюдает за работой, а не мешает ей.
    /// </summary>
    public int? UserId { get; set; }

    /// <summary>
    /// ФИО на момент изменения. Снимком, потому что ссылки нет: без него запись
    /// «пользователь № 77 поменял справочник» ничего не объясняет.
    /// </summary>
    public string? UserName { get; set; }

    public DateTime At { get; set; }
}
