namespace delosfera_server.Modules.Feedback.Models;

/// <summary>
/// Заход на экран системы.
///
/// Нужен, чтобы во время обкатки видеть правду вместо предположений: какие разделы
/// открывают, какие не открыли ни разу, кто из подразделений работает, а кто ещё не
/// начинал. Без этого об итогах обкатки судят по тому, кто громче написал.
///
/// Отдельная таблица, а не строка в журнале действий. Переходов на порядок больше,
/// чем действий с документами: пятьсот человек за день дают десятки тысяч записей, и
/// журнал, где ищут след конкретного документа, превратился бы в свалку.
///
/// Чего здесь намеренно нет: строки запроса. Она содержит то, что человек искал, а в
/// банке это может быть фамилия клиента или номер счёта. Ради статистики посещений
/// такой риск не берут — путь экрана отвечает на все нужные вопросы.
/// </summary>
public class PageVisit
{
    public long Id { get; set; }

    public int UserId { get; set; }
    public Users.Models.User? User { get; set; }

    /// <summary>
    /// Шаблон маршрута: «/sz/:id», а не «/sz/431». Иначе каждый документ считался бы
    /// отдельной страницей и в отчёте о популярности экранов не было бы смысла.
    /// </summary>
    public required string RoutePath { get; set; }

    /// <summary>Идентификатор из адреса, если он там был.</summary>
    public int? EntityId { get; set; }

    /// <summary>Заголовок экрана на момент захода — чтобы отчёт читался без словаря маршрутов.</summary>
    public string? Title { get; set; }

    public DateTime VisitedAt { get; set; }

    /// <summary>
    /// Сколько человек пробыл на экране, миллисекунд. Считает браузер и присылает
    /// вместе со следующим переходом, поэтому у последнего экрана сессии значения нет.
    /// Отличает «зашёл и работал» от «промахнулся мимо пункта меню».
    /// </summary>
    public int? DurationMs { get; set; }

    /// <summary>
    /// Метка вкладки браузера. Живёт до её закрытия и ни с чем не связана — нужна
    /// только чтобы отличить один сеанс работы от другого при подсчёте.
    /// </summary>
    public string? SessionKey { get; set; }
}
