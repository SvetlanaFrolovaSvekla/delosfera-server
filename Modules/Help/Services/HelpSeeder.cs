/// <summary>
/// Стартовый набор инструкций.
///
/// Заводится один раз — когда статей нет вовсе. Дальше их ведёт администратор, и
/// перезаписывать его правки при каждом запуске нельзя: инструкция принадлежит
/// банку, а не сборке.
///
/// Одна статья на процесс. Близкие сценарии сведены вместе там, где человек и так
/// делает их подряд: заявку на закупку не заводят отдельно от согласования, а
/// подписание не существует без согласования. Дробить их значило бы заставлять
/// читателя собирать одну задачу из трёх статей.
/// </summary>
public static class HelpSeeder
{
    public static void Seed(DelosferaDbContext db)
    {
        if (db.HelpArticles.Any()) return;

        var now = DateTime.UtcNow;

        foreach (var (article, body) in Articles())
        {
            article.BodyJson = JsonSerializer.Serialize(body,
                new JsonSerializerOptions {Encoder = System.Text.Encodings.Web.JavaScriptEncoder.UnsafeRelaxedJsonEscaping});
            article.IsPublished = true;
            article.CreatedAt = now;
            article.UpdatedAt = now;
            db.HelpArticles.Add(article);
        }

        db.SaveChanges();
    }

