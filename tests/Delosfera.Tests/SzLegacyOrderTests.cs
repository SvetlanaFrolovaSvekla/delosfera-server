using delosfera_server.Modules.Sz.Models;

namespace Delosfera.Tests;

/// <summary>
/// Порядок движения записки после завершения маршрута.
///
/// Регистрация идёт первой: записка получает номер в Секторе делопроизводства,
/// затем её согласуют и только потом подписывает руководство (адресат). Здесь
/// проверяется само правило перехода, без базы: куда ведёт завершённый маршрут,
/// зависит от того, какой это маршрут (согласование или подпись) и есть ли у
/// записки подписант с адресатом.
/// </summary>
public class SzLegacyOrderTests
{
    /// <summary>
    /// Куда ведёт завершённый маршрут. Повторяет условие из
    /// SzRouteCompletionHandler: идёт ли подписание, есть ли подписант, есть ли адресат.
    /// </summary>
    private static string ПослеМаршрута(bool наПодписи, bool естьПодписант, bool естьАдресат) =>
        (наПодписи, естьПодписант, естьАдресат) switch
        {
            // Согласование пройдено, подписант есть — записка уходит на подпись.
            (false, true, _) => SzStatus.OnSigning,

            // Подписано — записка на исполнении: подписывает адресат, он же
            // отписывает её резолюцией.
            (true, _, _) => SzStatus.OnExecution,

            // Подписанта нет, но есть адресат — к нему за решением по существу.
            (false, false, true) => SzStatus.OnAddresseeDecision,

            // Ни подписанта, ни адресата — сразу на исполнение.
            (false, false, false) => SzStatus.OnExecution,
        };

    [Fact]
    public void После_согласования_записка_идёт_на_подпись()
    {
        var статус = ПослеМаршрута(наПодписи: false, естьПодписант: true, естьАдресат: true);

        Assert.Equal(SzStatus.OnSigning, статус);
    }

    [Fact]
    public void После_подписания_записка_на_исполнении()
    {
        var статус = ПослеМаршрута(наПодписи: true, естьПодписант: true, естьАдресат: true);

        Assert.Equal(SzStatus.OnExecution, статус);
    }

    [Fact]
    public void Без_подписанта_записка_идёт_к_адресату()
    {
        var статус = ПослеМаршрута(наПодписи: false, естьПодписант: false, естьАдресат: true);

        Assert.Equal(SzStatus.OnAddresseeDecision, статус);
    }

    [Fact]
    public void Без_подписанта_и_адресата_записка_идёт_на_исполнение()
    {
        var статус = ПослеМаршрута(наПодписи: false, естьПодписант: false, естьАдресат: false);

        Assert.Equal(SzStatus.OnExecution, статус);
    }

    [Fact]
    public void Прежний_статус_остаётся_известным_системе()
    {
        // На стенде под ним лежат записки прежнего порядка: убрав его из перечня,
        // мы сделали бы их невидимыми в реестре и непроходимыми по фильтрам.
        Assert.Contains(SzStatus.Registered, SzStatus.All);
        Assert.Contains(SzStatus.Registered, SzStatus.Active);
    }
}
